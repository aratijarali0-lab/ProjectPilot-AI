def normalize(value):
    return " ".join(
        str(value or "").strip().lower().split()
    )


def resolve_key(value):
    normalized = normalize(value)

    for alias, actual in ALIASES.items():
        if normalized == normalize(alias):
            return actual

    for key in DATASETS:
        if normalized == normalize(key):
            return key

    return None


def get_datasets(
    skills=None,
    interests=None,
    limit=10,
):
    skills = skills or []
    interests = interests or []

    keys = []

    for value in (
        list(skills) +
        list(interests)
    ):
        key = resolve_key(value)

        if (
            key
            and key not in keys
        ):
            keys.append(key)

    result = []
    seen = set()

    for key in keys:

        for dataset in DATASETS[key]:

            url = dataset["url"]

            if url in seen:
                continue

            item = dict(dataset)

            item["matched_by"] = key

            result.append(item)

            seen.add(url)

            if len(result) >= limit:
                return result

    return result